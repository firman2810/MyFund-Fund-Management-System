export function buildInitialTransactions(allocations: Allocation[], distributions: Distribution[]): Transaction[] {
  const txList: Transaction[] = [];

  // Add allocation transactions
  allocations.forEach((alc) => {
    txList.push({
      id: `TX-ALC-${alc.id.replace('ALC-', '')}`,
      txHash: alc.blockchainRecord.txId,
      type: 'Fund Allocation',
      from: alc.allocatedBy,
      to: alc.receivingAgency,
      amount: alc.amount,
      date: alc.allocatedDate,
      status: 'Committed',
      programme: alc.programme,
      description: alc.description,
      referenceNo: alc.referenceNo,
      blockchainRecord: alc.blockchainRecord,
    });
  });

  // Add distribution transactions
  distributions.forEach((dst) => {
    txList.push({
      id: `TX-DST-${dst.id.replace('DST-', '')}`,
      txHash: dst.blockchainRecord.txId,
      type: 'Fund Distribution',
      from: dst.agencyName,
      to: `${dst.beneficiaryName} (${dst.beneficiaryId})`,
      amount: dst.amount,
      date: dst.distributedDate,
      status: 'Committed',
      programme: dst.programmeName,
      description: dst.description,
      referenceNo: dst.id,
      blockchainRecord: dst.blockchainRecord,
    });
  });

  // Sort descending by date
  return txList.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());
}
